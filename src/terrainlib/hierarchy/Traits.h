#pragma once

#include <concepts>

namespace hierarchy {

// Traits of keys that form a tree.
template <typename T>
concept Traits = requires(typename T::Key key) {
    { T::root() } -> std::same_as<typename T::Key>;
    T::parent(key);
    T::children(key);
};

} // namespace hierarchy
