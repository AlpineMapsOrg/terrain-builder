#pragma once

#include <algorithm>
#include <cstddef>

// A string literal usable as a template argument.
template <size_t Size>
struct FixedString {
    char value[Size];

    constexpr FixedString(const char (&text)[Size]) {
        std::copy_n(text, Size, value);
    }

    constexpr auto operator<=>(const FixedString &) const = default;
};
